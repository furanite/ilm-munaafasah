// Builds questions/isl-ayah.txt ("Complete the Ayah") and questions/quran-ref.json from a verified Uthmani text.
// Usage: node scripts/make-ayah.mjs path/to/quran-json/dist/quran.json
// Source text: the npm package quran-json@3.1.2, whose Uthmani text comes from The Noble Qur'an Encyclopedia
// (quranenc.com, King Fahd Complex Mushaf text). Clue and answer are cut only at spaces between words, so
// the Qur'anic text itself is never changed; tests/ayah.test.ts checks every line against quran-ref.json.
import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const quran = JSON.parse(readFileSync(process.argv[2], 'utf8'))
const text = (s, a) => quran[s - 1].verses[a - 1].text
const WAQF = /[ۖ-ۜ]/

// [surah:ayah, first word shown, words shown before the gap, last word of the answer (optional)]
// Without a last word, the answer runs to the next pause mark or the end of the ayah.
const LEVELS = {
  100: [['1:1', 0, 2], ['1:2', 0, 2], ['1:5', 0, 2], ['1:6', 0, 1], ['112:1', 0, 2], ['112:3', 0, 2], ['112:4', 0, 3], ['113:1', 0, 2], ['114:1', 0, 3], ['108:1', 0, 2], ['109:6', 0, 2], ['103:2', 0, 2], ['110:1', 0, 3], ['94:5', 0, 2], ['97:1', 0, 2]],
  200: [['1:7', 0, 4], ['113:2', 0, 2], ['114:4', 0, 3], ['108:3', 0, 2], ['110:2', 0, 3], ['110:3', 0, 4], ['103:3', 0, 5], ['105:1', 0, 4], ['106:3', 0, 1], ['106:4', 0, 4], ['107:1', 0, 2], ['111:1', 0, 2], ['97:3', 0, 2], ['99:7', 0, 4], ['95:4', 0, 3], ['96:1', 0, 2]],
  300: [['2:255', 0, 5], ['3:8', 0, 7], ['2:201', 3, 8], ['13:28', 6, 8], ['2:152', 0, 2], ['2:153', 6, 8], ['21:87', 13, 18], ['20:114', 13, 15], ['17:24', 6, 9], ['3:173', 12, 15], ['2:156', 5, 7], ['20:25', 0, 2], ['21:107', 0, 2], ['33:41', 0, 3], ['87:1', 0, 2], ['89:27', 0, 2], ['23:1', 0, 2], ['55:13', 0, 2]],
  400: [['24:35', 0, 2], ['2:186', 0, 4], ['65:3', 5, 9], ['33:56', 0, 4], ['49:13', 11, 15], ['39:53', 6, 8], ['3:185', 0, 2], ['2:2', 0, 2, 4], ['36:82', 0, 8], ['3:190', 0, 5], ['14:40', 0, 4], ['7:23', 1, 4], ['25:74', 2, 7], ['18:10', 6, 11], ['2:250', 5, 9], ['9:129', 2, 5], ['6:162', 0, 6], ['50:16', 8, 10], ['67:1', 0, 4], ['3:139', 0, 4], ['16:90', 0, 3, 4]],
  500: [['59:22', 0, 7], ['59:23', 7, 10, 11], ['59:24', 0, 3], ['3:26', 0, 4, 7], ['3:18', 0, 7], ['2:163', 0, 1, 2], ['42:11', 13, 16], ['28:88', 10, 12], ['35:28', 7, 10], ['47:7', 0, 6], ['64:16', 0, 4], ['8:2', 0, 6, 7], ['10:62', 0, 4], ['14:7', 0, 5], ['16:128', 0, 3], ['18:46', 5, 7], ['3:31', 0, 5], ['12:87', 6, 8], ['3:103', 0, 4], ['89:28', 0, 3], ['29:69', 5, 7]],
}

const ref = {}
let out = `id: isl-ayah
name: Complete the Ayah
nameAr: أكمل الآية
group: quran
# Generated by scripts/make-ayah.mjs from a verified Uthmani text. Do not edit by hand:
# the Qur'anic text must stay exactly as in the Mushaf (tests/ayah.test.ts checks it).
# The clue shows the start of a phrase; the answer is the words that follow.
`
for (const [lvl, list] of Object.entries(LEVELS)) {
  out += `\n## ${lvl}\n`
  for (const [r, start, cut, last] of list) {
    const [s, a] = r.split(':').map(Number)
    const t = text(s, a)
    ref[r] = t
    const w = t.split(' ')
    let end = last
    if (end === undefined) {
      end = w.length - 1
      for (let k = cut; k < w.length; k++) if (WAQF.test(w[k])) { end = k; break }
    }
    if (!(start >= 0 && start < cut && cut <= end && end < w.length)) throw new Error(`bad cut for ${r}`)
    const clue = w.slice(start, cut).join(' ')
    const ans = w.slice(cut, end + 1).join(' ')
    out += `${start ? '… ' : ''}${clue} … :: ${ans} (${r}) || H: Qur'an ${r}\n`
  }
}
writeFileSync(join(root, 'questions', 'isl-ayah.txt'), out)
writeFileSync(join(root, 'questions', 'quran-ref.json'), JSON.stringify({ source: "Uthmani text, The Noble Qur'an Encyclopedia (quranenc.com), via npm quran-json@3.1.2", ayat: ref }, null, 1) + '\n')
console.log('wrote', Object.values(LEVELS).flat().length, 'ayah questions')
